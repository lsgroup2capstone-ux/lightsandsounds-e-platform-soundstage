const { readFileSync } = require('node:fs')
const { transpileModule, ModuleKind } = require('typescript')
const Module = require('node:module')
const assert = require('node:assert/strict')
const storage = () => { const values = new Map(); return { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) } }
global.localStorage = storage(); global.sessionStorage = storage()
const file = new Module('admin-accounts-test')
file.require = name => name === "../runtime" ? { storage: global.localStorage, session: global.sessionStorage, events: { dispatchEvent() {} } } : ({})
file._compile(transpileModule(readFileSync('lib/server/domain/client-auth.ts', 'utf8'), { compilerOptions: { module: ModuleKind.CommonJS } }).outputText, 'admin-accounts-test.js')
localStorage.setItem('soundstage-accounts-v2', JSON.stringify(['client','provider'].map(role => ({ role, email: `${role}@example.com`, firstName: role, password: 'private-password', authMethod: 'email' }))))
assert.deepEqual(file.exports.getAccountsForAdmin(), [])
sessionStorage.setItem('soundstage-session', JSON.stringify({ role: 'client', email: 'client@example.com' }))
assert.deepEqual(file.exports.getAccountsForAdmin(), [])
localStorage.setItem('soundstage-admin-account', JSON.stringify({ role: 'admin', email: 'admin@example.com' }))
sessionStorage.setItem('soundstage-session', JSON.stringify({ role: 'admin', email: 'admin@example.com' }))
const accounts = file.exports.getAccountsForAdmin()
assert.deepEqual(accounts.map(a => a.role), ['client','provider'])
assert.ok(accounts.every(a => !Object.hasOwn(a, 'password')))
console.log('Admin account checks passed: both roles listed, passwords excluded, non-admin access denied.')
