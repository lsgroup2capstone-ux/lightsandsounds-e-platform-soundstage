const { test } = require('node:test')
const assert = require('node:assert/strict')
const { databaseConfig } = require('../scripts/database-config.cjs')
test('PostgreSQL config validates credentials and enforces TLS verification', () => {
  assert.throws(() => databaseConfig({}), /SUPABASE_DB_URL/)
  assert.throws(() => databaseConfig({ SUPABASE_DB_URL: '  ' }), { code: 'DATABASE_NOT_CONFIGURED' })
  assert.throws(() => databaseConfig({ SUPABASE_DB_URL: 'https://example.com' }), /PostgreSQL/)
  assert.throws(() => databaseConfig({ SUPABASE_DB_URL: 'postgres://user@host/db' }), /password/)
  const config = databaseConfig({ SUPABASE_DB_URL: 'postgresql://user:p%40ss@host:5432/postgres?sslmode=disable', SUPABASE_DB_CA: 'one\\ntwo' })
  assert.equal(config.options.ssl.rejectUnauthorized, true)
  assert.equal(config.options.ssl.ca, 'one\ntwo')
  assert.equal(config.options.prepare, false)
  assert.equal(new URL(config.url).searchParams.has('sslmode'), false)
  assert.equal(new URL(config.url).password, 'p%40ss')
})
